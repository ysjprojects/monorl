"""Data bridge: monorl samples → NeMo-RL response dataset + ``DatumSpec`` processor.

Targets NVIDIA-NeMo/RL **v0.7.0** (``81aa43dda4765b0429cf31dab44441e4e4383911``):

* ``nemo_rl/data/datasets/response_datasets/__init__.py::load_response_dataset`` resolves a dotted
  ``dataset_name`` (``resolve_external_dataset_class``), instantiates it with ``**data_config`` and
  calls ``set_task_spec(cfg)`` then ``set_processor()``; ``nemo_rl/data/utils.py::setup_response_data``
  then reads ``task_name``, ``dataset``, ``val_dataset``, ``task_spec``, ``processor``, ``preprocessor``.
* ``nemo_rl/data/datasets/processed_dataset.py::AllTaskProcessedDataset.__getitem__`` dispatches on the
  row's ``task_name`` column and calls ``processor(row, task_spec, tokenizer, max_seq_length, idx)``
  which must return a ``DatumSpec`` (``nemo_rl/data/interfaces.py``).
* Rows also carry ``input``/``output`` so the file loads with the stock ``ResponseDataset``.
* SFT (``algorithm.name: sft``) exports ``nemo_rl/sft_train.jsonl`` (+ ``sft_eval.jsonl``) rows of
  ``{"messages": [prompt..., assistant response]}`` for the stock ``ResponseDataset`` (keeps a
  ``messages`` column as-is, ``response_dataset.py``) and ``examples/run_sft.py``'s
  ``sft_processor`` (``nemo_rl/data/processors.py``: ``get_formatted_message_log`` per turn).

The run directory gets ``nemo_rl/train.jsonl`` (+ ``eval.jsonl``) and an importable shim module
``monorl_nemo_rl_data.py`` re-exporting :class:`MonorlDataset`; the launcher puts the run dir on
``PYTHONPATH`` so ``data.train.dataset_name: monorl_nemo_rl_data.MonorlDataset`` resolves.
"""

from __future__ import annotations

import json
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from monorl.config.schema import DataConfig, RunConfig
from monorl.core.errors import ConfigError
from monorl.core.types import Message, Sample, message_text, messages_have_media

#: ``task_name`` of every exported row and of every ``DatumSpec`` the processor emits.
TASK_NAME = "monorl"

#: Module written into the run dir (``<run_dir>/<MODULE_NAME>.py``).
MODULE_NAME = "monorl_nemo_rl_data"

#: Sub-directory of the run dir holding the NeMo-RL artefacts.
SUBDIR = "nemo_rl"

_SHIM_SOURCE = f'''"""Generated by monorl: NeMo-RL dataset bridge for this run (importable from the run dir)."""

from monorl.adapters.nemo_rl.data import MonorlDataset, monorl_data_processor

TASK_NAME = {TASK_NAME!r}

__all__ = ["MonorlDataset", "TASK_NAME", "monorl_data_processor"]
'''


@dataclass(frozen=True, slots=True)
class DataPaths:
    root: Path
    train_jsonl: Path
    eval_jsonl: Path
    module_path: Path
    sft_train_jsonl: Path
    sft_eval_jsonl: Path
    module_name: str = MODULE_NAME


def data_paths(run_dir: str | Path) -> DataPaths:
    run_dir = Path(run_dir).expanduser().resolve()
    root = run_dir / SUBDIR
    return DataPaths(
        root=root,
        train_jsonl=root / "train.jsonl",
        eval_jsonl=root / "eval.jsonl",
        module_path=run_dir / f"{MODULE_NAME}.py",
        sft_train_jsonl=root / "sft_train.jsonl",
        sft_eval_jsonl=root / "sft_eval.jsonl",
    )


# -- rows ------------------------------------------------------------------------------------


def _last_user_text(messages: list[Message]) -> str:
    for m in reversed(messages):
        if m.get("role") == "user":
            return str(m.get("content", ""))
    return str(messages[-1].get("content", "")) if messages else ""


def sample_to_row(sample: Sample) -> dict[str, Any]:
    """JSON row with a stable Arrow schema (nested/heterogeneous fields are JSON-encoded)."""
    reference = sample.reference
    return {
        "task_name": TASK_NAME,
        "sample_id": str(sample.id),
        "input": _last_user_text(sample.messages),
        "output": reference if isinstance(reference, str) else json.dumps(reference, default=str),
        "messages_json": json.dumps(list(sample.messages), default=str),
        "reference_json": json.dumps(reference, default=str),
        "metadata_json": json.dumps(dict(sample.metadata), default=str),
    }


def row_to_sample(row: dict[str, Any]) -> Sample:
    return Sample(
        id=str(row["sample_id"]),
        messages=json.loads(row["messages_json"]),
        reference=json.loads(row["reference_json"]),
        metadata=json.loads(row.get("metadata_json") or "{}"),
    )


def export_jsonl(samples: Iterable[Sample], path: str | Path) -> int:
    """Write ``samples`` as jsonl rows; returns the row count."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    count = 0
    with open(path, "w") as f:
        for sample in samples:
            f.write(json.dumps(sample_to_row(sample)) + "\n")
            count += 1
    return count


def sft_sample_to_row(sample: Sample, *, response_field: str | None) -> dict[str, Any]:
    """``{"messages": prompt + assistant response}`` (text only: NeMo-RL's ``sft_processor`` renders
    each turn through the tokenizer chat template)."""
    from monorl.orchestrator.sft import sft_messages

    messages = sft_messages(sample, response_field=response_field)
    if messages_have_media(messages):
        raise ConfigError(
            "trainer.backend='nemo_rl' SFT takes text-only chats; NeMo-RL v0.7.0 trains VLMs through its own "
            "datasets (examples/run_vlm_sft.py), not through monorl image parts"
        )
    return {"messages": [{"role": str(m.get("role", "user")), "content": message_text(m)} for m in messages]}


def export_sft_jsonl(samples: Iterable[Sample], path: str | Path, *, response_field: str | None) -> int:
    """Write SFT chat rows; returns the row count."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    count = 0
    with open(path, "w") as f:
        for sample in samples:
            f.write(json.dumps(sft_sample_to_row(sample, response_field=response_field)) + "\n")
            count += 1
    return count


@dataclass(frozen=True, slots=True)
class ExportedData:
    paths: DataPaths
    num_train: int
    num_eval: int | None


def _eval_config(data: DataConfig) -> DataConfig:
    return data.model_copy(update={"uri": data.eval_uri, "split": data.eval_split, "eval_uri": None, "limit": None})


def export_dataset(config: RunConfig, run_dir: str | Path, *, tokenizer: Any = None) -> ExportedData:
    """Materialise ``config.data`` (and ``eval_uri``) through :func:`monorl.data.open_source`
    into ``<run_dir>/nemo_rl/{train,eval}.jsonl`` (``sft_{train,eval}.jsonl`` for SFT)."""
    from monorl.data import open_source

    paths = data_paths(run_dir)
    sft = config.is_sft
    response_field = config.data.response_field
    train = open_source(config.data, tokenizer=tokenizer, seed=config.seed)
    if sft:
        num_train = export_sft_jsonl(train, paths.sft_train_jsonl, response_field=response_field)
    else:
        num_train = export_jsonl(train, paths.train_jsonl)
    num_eval = None
    if config.data.eval_uri is not None:
        evaluation = open_source(_eval_config(config.data), tokenizer=tokenizer, seed=config.seed)
        if sft:
            num_eval = export_sft_jsonl(evaluation, paths.sft_eval_jsonl, response_field=response_field)
        else:
            num_eval = export_jsonl(evaluation, paths.eval_jsonl)
    return ExportedData(paths=paths, num_train=num_train, num_eval=num_eval)


def write_bridge_module(run_dir: str | Path) -> Path:
    """Write the importable shim module into the run dir; returns its path."""
    paths = data_paths(run_dir)
    paths.module_path.parent.mkdir(parents=True, exist_ok=True)
    paths.module_path.write_text(_SHIM_SOURCE)
    return paths.module_path


# -- DatumSpec processor ---------------------------------------------------------------------


def monorl_data_processor(
    datum_dict: dict[str, Any],
    task_data_spec: Any,
    tokenizer: Any,
    max_seq_length: int | None,
    idx: int,
) -> dict[str, Any]:
    """``TaskDataProcessFnCallable``: exported row → ``DatumSpec``.

    Mirrors ``math_hf_data_processor`` (``nemo_rl/data/processors.py`` v0.7.0): the whole chat is
    rendered with the tokenizer's chat template into one ``user`` context message carrying
    ``token_ids``; prompts at/over ``max_seq_length`` are truncated and masked with
    ``loss_multiplier=0``. ``task_data_spec.system_prompt``/``prompt`` (NeMo-RL prompt files) are
    honoured when set; monorl's own ``system_prompt``/``prompt_template`` were already applied at export.
    """
    sample = row_to_sample(datum_dict)
    messages: list[Message] = [dict(m) for m in sample.messages]
    system_prompt = getattr(task_data_spec, "system_prompt", None)
    if system_prompt and not (messages and messages[0].get("role") == "system"):
        messages.insert(0, {"role": "system", "content": system_prompt})
    prompt = getattr(task_data_spec, "prompt", None)
    if prompt:
        for m in reversed(messages):
            if m.get("role") == "user":
                m["content"] = prompt.format(m.get("content", ""))
                break
    text = tokenizer.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True, add_special_tokens=False
    )
    token_ids = tokenizer(text, return_tensors="pt", add_special_tokens=False)["input_ids"][0]
    message_log = [{"role": "user", "content": text, "token_ids": token_ids}]
    length = int(token_ids.shape[0])
    loss_multiplier = 1.0
    if max_seq_length is not None and length >= max_seq_length:
        message_log[0]["token_ids"] = token_ids[: min(4, max_seq_length)]
        loss_multiplier = 0.0
    return {
        "message_log": message_log,
        "length": length,
        "extra_env_info": {
            "sample_id": sample.id,
            "messages": messages,
            "reference": sample.reference,
            "metadata": sample.metadata,
        },
        "loss_multiplier": loss_multiplier,
        "idx": idx,
        "task_name": TASK_NAME,
    }


class MonorlDataset:
    """NeMo-RL response dataset over a monorl jsonl export (duck-types ``RawDataset``).

    Instantiated by ``load_response_dataset`` with the whole dataset config as keyword arguments;
    only ``data_path``/``split_validation_size``/``seed`` are used, the rest (``prompt_file``,
    ``env_name``, ``processor``…) is consumed by :meth:`set_task_spec`.
    """

    task_name = TASK_NAME
    preprocessor = None

    def __init__(
        self,
        data_path: str,
        split_validation_size: float = 0,
        seed: int = 42,
        **_: Any,
    ) -> None:
        from datasets import load_dataset

        self.data_path = data_path
        self.dataset = load_dataset("json", data_files=str(data_path))["train"]
        if "task_name" not in self.dataset.column_names:
            self.dataset = self.dataset.add_column("task_name", [TASK_NAME] * len(self.dataset))
        self.val_dataset = None
        self.processor = monorl_data_processor
        self.task_spec: Any = None
        self.data_config: dict[str, Any] = {}
        if split_validation_size and split_validation_size > 0:
            if split_validation_size >= 1:
                split_validation_size = int(split_validation_size)
            split = self.dataset.train_test_split(test_size=split_validation_size, seed=seed)
            self.dataset, self.val_dataset = split["train"], split["test"]

    def set_task_spec(self, data_config: dict[str, Any]) -> None:
        from nemo_rl.data.interfaces import TaskDataSpec

        self.data_config = dict(data_config)
        self.task_spec = TaskDataSpec(
            task_name=TASK_NAME,
            prompt_file=data_config.get("prompt_file"),
            system_prompt_file=data_config.get("system_prompt_file"),
        )

    def set_processor(self) -> None:
        self.processor = monorl_data_processor


