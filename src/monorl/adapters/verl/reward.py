"""Reward bridge: verl's ``custom_reward_function`` -> :func:`monorl.rewards.build_reward`.

verl v0.9.1 loads ``reward.custom_reward_function.path`` as a module and calls
``<name>(data_source=, solution_str=, ground_truth=, extra_info=)`` from the reward manager
(``verl/trainer/ppo/reward.py::get_custom_reward_fn``,
``verl/experimental/reward_loop/reward_manager/naive.py::run_single``). A dict return is accepted:
``result["score"]`` is the reward, every other key lands in ``reward_extra_info``.

:func:`write_reward_module` writes ``<run_dir>/monorl_reward.py`` which embeds the serialised
:class:`~monorl.config.schema.RewardSpec` list and delegates to :class:`RewardBridge`.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from monorl.adapters.verl.data import DATA_SOURCE, decode_reference
from monorl.config.schema import RewardSpec, RunConfig
from monorl.core.types import Completion, Sample, Trajectory, Turn

REWARD_MODULE = "monorl_reward.py"
REWARD_FUNCTION_NAME = "compute_score"


def reward_module_path(run_dir: str | Path) -> Path:
    return Path(run_dir) / REWARD_MODULE


def trajectory_from_verl(
    solution_str: str, ground_truth: Any, extra_info: dict[str, Any] | None, *, data_source: str = DATA_SOURCE
) -> Trajectory:
    """Rebuild the monorl :class:`Trajectory` the reward functions expect from verl's reward-manager call."""
    info = dict(extra_info or {})
    try:
        messages = json.loads(info["messages_json"]) if info.get("messages_json") else []
    except (TypeError, ValueError):
        messages = []
    try:
        metadata = json.loads(info["metadata_json"]) if info.get("metadata_json") else {}
    except (TypeError, ValueError):
        metadata = {}
    sample = Sample(
        id=str(info.get("sample_id") or info.get("index", "")),
        messages=messages,
        reference=decode_reference(ground_truth, info.get("reference_encoding")),
        metadata=metadata,
    )
    completion = Completion(text=str(solution_str), token_ids=[], finish_reason="stop")
    turn = Turn(prompt_token_ids=[], completion=completion)
    num_turns = info.get("num_turns")
    return Trajectory(
        sample=sample,
        group_id=str(info.get("index", sample.id)),
        messages=[*messages, {"role": "assistant", "content": str(solution_str)}],
        turns=[turn],
        info={
            "data_source": data_source,
            "num_turns": num_turns,
            "rollout_reward_scores": info.get("rollout_reward_scores"),
        },
    )


class RewardBridge:
    """Builds the composite reward once and scores verl samples one at a time."""

    def __init__(self, specs: list[dict[str, Any]], config_path: str | Path | None = None) -> None:
        from monorl.rewards import build_reward

        self.specs = [RewardSpec.model_validate(s) for s in specs]
        self.config = RunConfig.from_yaml(config_path) if config_path and Path(config_path).exists() else None
        self.reward = build_reward(self.specs, config=self.config)

    def __call__(
        self,
        data_source: str,
        solution_str: str,
        ground_truth: Any,
        extra_info: dict[str, Any] | None = None,
        **_: Any,
    ) -> dict[str, float]:
        traj = trajectory_from_verl(solution_str, ground_truth, extra_info, data_source=data_source)
        result = self.reward([traj])[0]
        out: dict[str, float] = {"score": float(result.score)}
        for key, value in result.breakdown.items():
            out[f"reward/{key}"] = float(value)
        return out


_MODULE_TEMPLATE = '''"""Generated by monorl: verl ``custom_reward_function`` for this run (do not edit)."""

from monorl.adapters.verl.reward import RewardBridge

REWARD_SPECS = {specs}
CONFIG_PATH = {config_path}

_bridge = None


def {name}(data_source, solution_str, ground_truth, extra_info=None, **kwargs):
    global _bridge
    if _bridge is None:
        _bridge = RewardBridge(REWARD_SPECS, CONFIG_PATH)
    return _bridge(data_source, solution_str, ground_truth, extra_info, **kwargs)
'''


def write_reward_module(
    config: RunConfig, run_dir: str | Path, *, config_path: str | Path | None = None
) -> Path:
    """Write ``<run_dir>/monorl_reward.py`` exposing ``compute_score`` for ``config.rewards``."""
    if not config.rewards:
        raise ValueError("verl backend needs at least one entry in `rewards`")
    path = reward_module_path(run_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    specs = [spec.model_dump(mode="json") for spec in config.rewards]
    path.write_text(
        _MODULE_TEMPLATE.format(
            specs=repr(specs),
            config_path=repr(str(config_path) if config_path else None),
            name=REWARD_FUNCTION_NAME,
        )
    )
    return path
